// ---- Rust core (crates/vehicle-ffi) ----

val repoRoot = rootDir.resolve("../..")
val rustJniLibs = layout.buildDirectory.dir("rustJniLibs")
val uniffiKotlin = layout.buildDirectory.dir("generated/uniffi")
val rustProfile = "release"

val cargoBuildAndroid = tasks.register<Exec>("cargoBuildAndroid") {
    description = "Builds libvehicle_ffi.so for the Android ABIs with cargo-ndk."
    workingDir = repoRoot
    commandLine(
        "cargo", "ndk",
        "-t", "x86_64", "-t", "arm64-v8a",
        "-o", rustJniLibs.get().asFile.path,
        "build", "--$rustProfile", "-p", "vehicle-ffi", "--lib",
    )
    inputs.dir(repoRoot.resolve("crates"))
    inputs.file(repoRoot.resolve("Cargo.lock"))
    outputs.dir(rustJniLibs)
}

val generateUniffiKotlin = tasks.register<Exec>("generateUniffiKotlin") {
    description = "Generates Kotlin bindings from the built Rust library."
    dependsOn(cargoBuildAndroid)
    workingDir = repoRoot
    commandLine(
        "cargo", "run", "-q", "-p", "vehicle-ffi", "--features", "bindgen", "--bin", "uniffi-bindgen", "--",
        "generate", "--library", "target/x86_64-linux-android/$rustProfile/libvehicle_ffi.so",
        "--language", "kotlin", "--no-format", "--out-dir", uniffiKotlin.get().asFile.path,
    )
    inputs.dir(rustJniLibs)
    outputs.dir(uniffiKotlin)
}

tasks.named("preBuild") { dependsOn(generateUniffiKotlin) }

android {
    namespace = "app.rustbenz"
    // Compose 1.13 requires compiling against API 37.1.
    compileSdk { version = release(37) { minorApiLevel = 1 } }

    defaultConfig {
        applicationId = "app.rustbenz"
        minSdk = 28
        targetSdk = 36
        versionCode = 1
        versionName = "0.1.0"
        ndk { abiFilters += listOf("x86_64", "arm64-v8a") }
    }

    buildFeatures { compose = true }

    // Generated by the tasks above; preBuild depends on them.
    sourceSets["main"].jniLibs.directories.add(rustJniLibs.get().asFile.path)
    sourceSets["main"].kotlin.directories.add(uniffiKotlin.get().asFile.path)
}

